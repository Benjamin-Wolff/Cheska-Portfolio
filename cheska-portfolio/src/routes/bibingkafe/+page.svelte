<h3 class="text-xl font-normal mb-4 text-green-800">
	Bibingkafe is a family-owned business established in 2015, inspired by my grandmother's homemade bibingka recipe. Bibingka is a traditional Filipino rice cake, commonly enjoyed during the holiday season. What started with a recipe my family loved became an opportunity to share one of our favorite Filipino treats with others.
</h3>

<h3 class="text-xl font-normal mb-4 text-green-800">
	Over the years, I've supported Bibingkafe on the social media and marketing side whenever needed. Most recently, I worked closely with my dad to completely rebrand the business, including creating a new logo and refreshing the overall look and feel of Bibingkafe.
</h3>

<h3 class="text-xl font-normal mb-4 text-green-800">
	More recently, we've brought Bibingkafe back into the community through pop-ups in NYC, connecting with new customers and sharing my grandmother's recipe beyond our family.
</h3>

<h3 class="text-xl font-normal text-green-800">
	Being able to contribute to a family business while applying my marketing and creative skills has made Bibingkafe one of my favorite projects to work on.
</h3>
